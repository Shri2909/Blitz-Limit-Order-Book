#!/usr/bin/env python3
"""
Exports every calibration constant new-feature/include/asmm/calibration.hpp
needs, at full float precision, by re-running the already-validated analysis
functions directly (not by parsing/re-typing the 4-decimal text in
output_*.txt). Prints a ready-to-paste C++ header.

Per final_plan.md's own rule: the sigma-bucket table and composite weights
must be "pulled directly... at implementation time" rather than hand
transcribed -- this script IS that extraction, done once, programmatically.

SUPERSEDED for sigma_cents_buckets and gamma_default: sigma_buckets() below
computes np.std(np.diff(sub)) on raw tick-level mids, with no fixed-dt
resampling and no /sqrt(dt) scaling -- found, after the first backtest run,
to be systematically smaller than the session-level sigma (which DOES use a
1-second grid) computed elsewhere, silently understating live inventory
control and (for STANDARD_K names) the k-based spread. calibration.hpp's
sigma_cents_buckets and gamma_default now come from
new-feature/analysis/derive_gamma_skew.py instead -- see that script's
docstring and calibration.hpp's "RECALIBRATION NOTE". k_bid/k_ask, the
composite OLS weights, and skew_strength_default's method are unaffected by
that bug and this script's numbers for those still agree with
derive_gamma_skew.py's.
"""
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from analyze_dataset import SESSION_END_S, SESSION_START_S, TICKERS  # noqa: E402
from analyze_dataset_alpha import compute_ofi_events  # noqa: E402
from analyze_dataset_alpha2 import MOMENTUM_WINDOW_S, grid_index, stream_depth  # noqa: E402
from analyze_dataset_alpha3 import build_component_grids, zscore  # noqa: E402
from analyze_dataset_deep import fit_lambda_delta  # noqa: E402

TICKERS_WITH_MICRO = {"INTC", "MSFT"}
N_BUCKETS = 13


def sigma_buckets(times, mids):
    edges = np.linspace(SESSION_START_S, SESSION_END_S, N_BUCKETS + 1)
    out = []
    for i in range(N_BUCKETS):
        t0, t1 = edges[i], edges[i + 1]
        mask = (times >= t0) & (times < t1)
        sub = mids[mask]
        out.append(float(np.std(np.diff(sub))) if len(sub) > 2 else float("nan"))
    return out


def k_bid_ask(d, mids_before, session_seconds):
    is_lit = d["etypes"] == 4
    deltas_lit = np.abs(d["prices"][is_lit] - mids_before[is_lit]) * 100.0
    lit_dir = d["directions"][is_lit]
    k_bid, _, _, _ = fit_lambda_delta(deltas_lit[lit_dir == 1], session_seconds)
    k_ask, _, _, _ = fit_lambda_delta(deltas_lit[lit_dir == -1], session_seconds)
    return k_bid, k_ask


def main():
    print("// AUTO-GENERATED by new-feature/analysis/export_calibration.py -- do not hand-edit")
    print("// Every value below is re-derived at full float precision from the validated")
    print("// analysis functions, not copied from the 4-decimal text in output_*.txt.")
    print()

    for ticker in TICKERS:
        d = stream_depth(ticker)
        mids = (d["ask_p1"] + d["bid_p1"]) / 2.0
        mids_before = np.empty_like(mids)
        mids_before[0] = mids[0]
        mids_before[1:] = mids[:-1]
        session_seconds = SESSION_END_S - SESSION_START_S

        sig_buckets = sigma_buckets(d["times"], mids)
        k_bid, k_ask = k_bid_ask(d, mids_before, session_seconds)

        grid = np.arange(SESSION_START_S, SESSION_END_S, 1.0)
        idx_last = grid_index(d["times"], grid)
        bucket_idx = np.clip(np.searchsorted(grid, d["times"], side="right") - 1, 0, len(grid) - 1)

        ofi_grid, mom_grid, micro_grid = build_component_grids(d, grid, idx_last, bucket_idx)
        ofi_std = float(ofi_grid.std())

        print(f"// ---- {ticker} ----")
        print(f"// sigma per half-hour bucket ($/sqrt(s)), 09:30-16:00, 13 buckets:")
        print("//   " + ", ".join(f"{v:.8f}" for v in sig_buckets))
        print(f"// OFI std (shares/s, full session): {ofi_std:.6f}")

        if ticker in TICKERS_WITH_MICRO:
            # fit composite OLS weights on FULL session (v1 uses fixed constants,
            # not the walk-forward split used only to validate the approach)
            components = {"OFI": ofi_grid, "TradeFlowMom": mom_grid, "MicroDev": micro_grid}
            z = [zscore(v) for v in components.values()]
            mid_grid = mids[idx_last]
            fwd = np.full_like(mid_grid, np.nan)
            fwd[:-5] = mid_grid[5:] - mid_grid[:-5]
            valid = ~np.isnan(fwd)
            X = np.column_stack(z)[valid]
            y = fwd[valid]
            beta, *_ = np.linalg.lstsq(np.column_stack([X, np.ones(len(X))]), y, rcond=None)
            composite_score = X @ beta[:-1]
            composite_std = float(composite_score.std())
            print(f"// composite OLS weights (OFI, TradeFlowMom, MicroDev, intercept): "
                  f"{beta[0]:.8f}, {beta[1]:.8f}, {beta[2]:.8f}, {beta[3]:.8f}")
            print(f"// composite score std (full session): {composite_std:.6f}")
        else:
            print(f"// k_bid={k_bid:.6f}/c  k_ask={k_ask:.6f}/c")
        print()


if __name__ == "__main__":
    sys.exit(main())
